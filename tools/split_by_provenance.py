#!/usr/bin/env python3
"""Split canonical particle/decay files into non-overlapping provenance layers.

The production tables mix two kinds of species: hadrons the PDG assigns a
Monte-Carlo ID, and quark-model states carrying an ad-hoc ID because no PDG
entry exists. Those have very different standing -- one is measured, the other
is a model prediction -- and a single file hides which is which.

Layers are written so that concatenating them reproduces the input exactly:

    <stem>_pdg      species PDG knows, and the channels closed within them
    <stem>_qm       the rest, plus every channel bridging the two

A bridge channel has a PDG-numbered parent and at least one quark-model
daughter (Delta(2420)- -> Delta(2400)- gamma). It belongs to the QM layer
because it only exists if the quark-model state does; moving it there is what
leaves the PDG layer closed and runnable on its own. The canonical decay format
carries the parent ID on every row, so a channel can live in a different file
from its particle header -- the same mechanism the charm/bottom supplement uses
to refer to light daughters.

This operates on canonical files, not AZYHYDRO: the AZYHYDRO layout requires
channels to follow their parent's header, which makes bridge channels
inexpressible.

Membership is decided by asking PDG, not by inspecting the digits. The 9xxxxxx
range is PDG's own for exotic and unconfirmed states -- 9000221 is f0(500) --
so an ID-magnitude test wrongly calls those invented, while short ad-hoc IDs
like 910 (Delta(2420)-) slip past it the other way.

    python tools/split_by_provenance.py \\
        data/particles_QM2016Plus_isofix.dat data/decays_QM2016Plus_isofix.dat \\
        --stem light

Requires the `pdg` package, as tools/audit_pdg.py and gen_heavy_flavour.py do.
"""
import argparse
import sys
from pathlib import Path

import pdg


def read_canonical(path):
    """(header_comment_lines, [row_fields, ...])"""
    header, rows = [], []
    for line in Path(path).read_text().splitlines():
        if line.startswith("#"):
            header.append(line)
        elif line.split():
            rows.append(line.split())
    return header, rows


def pdg_membership(api, ids):
    """{id: True/False} -- does PDG assign this Monte-Carlo ID?"""
    known = {}
    for particle_id in ids:
        try:
            api.get_particle_by_mcid(particle_id)
            known[particle_id] = True
        except Exception:
            known[particle_id] = False
    return known


def write(path, first_line, note, column_comment, rows):
    with open(path, "w") as handle:
        handle.write(first_line + "\n")
        handle.write("# generated by tools/split_by_provenance.py\n")
        for line in note:
            handle.write(f"# {line}\n")
        handle.write(column_comment + "\n")
        for row in rows:
            handle.write(" ".join(row) + "\n")
    return len(rows)


def quark_digits(mcid):
    """The three quark-content digits of a Monte-Carlo ID."""
    text = str(abs(mcid)).zfill(4)
    return {int(text[-4]), int(text[-3]), int(text[-2])}


def split_flavour(arguments):
    """Charm sector against bottom sector, by quark content.

    Net flavour will not do: quarkonia (J/psi, Upsilon, chi_c, chi_b) carry
    C = 0 and Bot = 0 because quark and antiquark cancel, so a net-number test
    files 32 of the 150 species under neither heading. Quark content puts
    charmonium with charm and bottomonium with bottom, which is what a
    heavy-flavour study means by the two sectors.

    Bottom is listed second because a b-hadron can feed a charm one; in this
    table it never does, since the weakly-decaying b-hadrons are terminal.
    """
    _, particle_rows = read_canonical(arguments.particles)
    _, decay_rows = read_canonical(arguments.decays)

    bottom = {int(r[0]) for r in particle_rows if 5 in quark_digits(int(r[0]))}
    charm = {int(r[0]) for r in particle_rows
             if int(r[0]) not in bottom and 4 in quark_digits(int(r[0]))}
    leftover = {int(r[0]) for r in particle_rows} - bottom - charm
    if leftover:
        raise SystemExit(f"species with neither charm nor bottom content: {sorted(leftover)[:5]}")

    source = f"split of {Path(arguments.particles).name} / {Path(arguments.decays).name}"
    outdir, stem = Path(arguments.outdir), arguments.stem
    particle_columns = "# id name mass width degeneracy B S C Bot I Q [aliases...]"
    decay_columns = "# parent n_daughters branching_fraction daughters..."

    for label, members, note in (("charm", charm, "charm sector: open charm and charmonium"),
                                 ("bottom", bottom, "bottom sector: open bottom and bottomonium")):
        write(outdir / f"particles_{label}.dat", "# FastReso canonical particles v1",
              [source, note], particle_columns,
              [r for r in particle_rows if int(r[0]) in members])
        rows = [r for r in decay_rows if int(r[0]) in members]
        write(outdir / f"decays_{label}.dat", "# FastReso canonical decays v1",
              [source, note, "daughters may live in the light layers -- load those too"],
              decay_columns, rows)
        print(f"  {label}: {sum(1 for r in particle_rows if int(r[0]) in members)} species, "
              f"{len(rows)} channels")
    return 0


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("particles", help="canonical particle file")
    parser.add_argument("decays", help="canonical decay file")
    parser.add_argument("--stem", required=True, help="output stem, e.g. 'light'")
    parser.add_argument("--outdir", default="data")
    parser.add_argument("--split", choices=("provenance", "flavour"),
                        default="provenance",
                        help="provenance: PDG-numbered vs quark-model. "
                             "flavour: charm sector vs bottom sector.")
    arguments = parser.parse_args(argv)
    if arguments.split == "flavour":
        return split_flavour(arguments)

    particle_header, particle_rows = read_canonical(arguments.particles)
    decay_header, decay_rows = read_canonical(arguments.decays)

    species = [int(row[0]) for row in particle_rows]
    daughters = {
        int(row[3 + i]) for row in decay_rows for i in range(int(row[1]))
    }
    api = pdg.connect()
    known = pdg_membership(api, set(species) | daughters)

    pdg_species = {i for i in species if known[i]}

    def closed(row):
        return all(known[int(row[3 + i])] for i in range(int(row[1])))

    # Partition by parent, not by channel. `merge` treats a parent's channel
    # block as all-or-nothing, so a parent whose channels were split across two
    # files is rejected as a conflicting definition. A PDG-numbered parent with
    # any quark-model daughter therefore hands its whole block to the QM layer;
    # its header stays in the PDG layer, where it reads as terminal.
    parents = {}
    for row in decay_rows:
        parents.setdefault(int(row[0]), []).append(row)
    qm_parents = {
        parent for parent, rows in parents.items()
        if parent not in pdg_species or not all(closed(r) for r in rows)
    }

    pdg_particles = [r for r in particle_rows if known[int(r[0])]]
    qm_particles = [r for r in particle_rows if not known[int(r[0])]]
    pdg_decays = [r for r in decay_rows if int(r[0]) not in qm_parents]
    qm_decays = [r for r in decay_rows if int(r[0]) in qm_parents]
    bridge = sum(1 for r in qm_decays if int(r[0]) in pdg_species)

    source = f"split of {Path(arguments.particles).name} / {Path(arguments.decays).name}"
    outdir = Path(arguments.outdir)
    stem = arguments.stem
    particle_columns = "# id name mass width degeneracy B S C Bot I Q [aliases...]"
    decay_columns = "# parent n_daughters branching_fraction daughters..."

    write(outdir / f"particles_{stem}_pdg.dat", "# FastReso canonical particles v1",
          [source, "species with a PDG Monte-Carlo ID"], particle_columns, pdg_particles)
    write(outdir / f"decays_{stem}_pdg.dat", "# FastReso canonical decays v1",
          [source, "channels whose parent and daughters are all PDG-numbered",
           "closed: loadable without the QM layer"], decay_columns, pdg_decays)
    write(outdir / f"particles_{stem}_qm.dat", "# FastReso canonical particles v1",
          [source, "quark-model states: no PDG Monte-Carlo ID exists"],
          particle_columns, qm_particles)
    write(outdir / f"decays_{stem}_qm.dat", "# FastReso canonical decays v1",
          [source, "channels involving at least one quark-model state",
           f"includes {bridge} channels whose parent is PDG-numbered: their",
           "headers live in the _pdg layer, so load both. A parent's whole block",
           "moves together because merge rejects a split block as a conflict."],
          decay_columns, qm_decays)

    print(f"  {stem}_pdg: {len(pdg_particles)} species, {len(pdg_decays)} channels")
    print(f"  {stem}_qm : {len(qm_particles)} species, {len(qm_decays)} channels "
          f"({bridge} bridge)")
    if not qm_particles and not qm_decays:
        print(f"  (no quark-model content: {stem} is entirely PDG-numbered)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
