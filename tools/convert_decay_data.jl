#!/usr/bin/env julia

"""
Convert supported external particle/decay formats to FastReso's canonical
split files. This tool is deliberately separate from the runtime reader.
"""
module DecayDataConverter

if isdefined(Main, :CascadeTables) &&
        isdefined(Main.CascadeTables, :ParticleList)
    # Reuse the runtime model types when a test or notebook loaded the core
    # first. Standalone CLI execution instead includes the lightweight model.
    const PL = Main.CascadeTables.ParticleList
else
    include(joinpath(@__DIR__, "..", "ParticleList.jl"))
    const PL = ParticleList
end

include(joinpath(@__DIR__, "converters", "AZYHYDRO.jl"))
include(joinpath(@__DIR__, "converters", "THERMINATOR.jl"))

export convert_azyhydro, convert_therminator, main

const USAGE = """
usage:
  julia --project=. tools/convert_decay_data.jl azyhydro INPUT... \\
      --particles-out PARTICLES --decays-out DECAYS [--force]

  julia --project=. tools/convert_decay_data.jl therminator PARTICLES DECAYS \\
      --particles-out PARTICLES_OUT --decays-out DECAYS_OUT \\
      [--cgc CGC] [--force]

The output convention is:
  particle: id name mass width degeneracy B S C Bot I Q [aliases...]
  decay:    parent n_daughters branching_fraction daughters...
"""

_floattext(value::Float64) = repr(value)

function _token(value, description)
    token = String(value)
    isempty(token) && throw(ArgumentError("$description cannot be empty"))
    any(isspace, token) && throw(ArgumentError(
        "$description $(repr(token)) contains whitespace and cannot be " *
            "represented in the canonical format",
    ))
    occursin('#', token) && throw(ArgumentError(
        "$description $(repr(token)) contains the reserved comment marker #",
    ))
    return token
end

function _catalogaliases(catalog::PL.ParticleCatalog, particle_id::Int)
    canonical_name = catalog.byid[particle_id].name
    aliases = String[]
    for (label, ids) in catalog.byname
        label == canonical_name && continue
        particle_id in ids && push!(aliases, label)
    end
    return sort!(unique!(aliases))
end

function _writeprovenance(io, kind, path, sha)
    println(io, "# FastReso canonical $kind v1")
    println(io, "# generated by tools/convert_decay_data.jl")
    isempty(path) || println(io, "# source: ", replace(path, '\n' => ' '))
    isempty(sha) || println(io, "# source-sha256: ", sha)
    return nothing
end

function _writeparticles(io, catalog::PL.ParticleCatalog)
    _writeprovenance(io, "particles", catalog.path, catalog.sha)
    println(io, "# id name mass width degeneracy B S C Bot I Q [aliases...]")
    for particle_id in sort!(collect(keys(catalog.byid)))
        particle = catalog.byid[particle_id]
        name = _token(particle.name, "particle name")
        aliases = [
            _token(alias, "particle alias")
            for alias in _catalogaliases(catalog, particle_id)
        ]
        fields = String[
            string(particle.id),
            name,
            _floattext(particle.mass),
            _floattext(particle.width),
            _floattext(particle.degeneracy),
            string(particle.baryon),
            string(particle.strangeness),
            string(particle.charm),
            string(particle.bottomness),
            _floattext(particle.twiceisospin / 2),
            string(particle.charge),
        ]
        append!(fields, aliases)
        println(io, join(fields, ' '))
    end
    return nothing
end

function _writedecays(io, network::PL.DecayNetwork)
    _writeprovenance(io, "decays", network.path, network.sha)
    println(io, "# parent n_daughters branching_fraction daughters...")
    for parent_id in sort!(collect(keys(network.byparent)))
        for channel in network.byparent[parent_id]
            fields = String[
                string(channel.parent),
                string(length(channel.daughters)),
                _floattext(channel.br),
            ]
            append!(fields, string.(channel.daughters))
            println(io, join(fields, ' '))
        end
    end
    return nothing
end

function _pathidentity(path::AbstractString)
    absolute_path = abspath(path)
    ispath(absolute_path) && return realpath(absolute_path)
    parent = dirname(absolute_path)
    resolved_parent = isdir(parent) ? realpath(parent) : normpath(parent)
    return joinpath(resolved_parent, basename(absolute_path))
end

function _samepath(left::AbstractString, right::AbstractString)
    _pathidentity(left) == _pathidentity(right) && return true
    return ispath(left) && ispath(right) &&
        Base.Filesystem.samefile(left, right)
end

function _validatetargets(
        particle_output::AbstractString,
        decay_output::AbstractString,
        inputs;
        force::Bool,
    )
    _samepath(particle_output, decay_output) && throw(ArgumentError(
        "particle and decay outputs must be different files",
    ))

    for (description, output) in (
            ("particle output", particle_output),
            ("decay output", decay_output),
        )
        for input in inputs
            _samepath(output, input) && throw(ArgumentError(
                "$description would overwrite an input file: " *
                    _pathidentity(input),
            ))
        end
        ispath(output) && !isfile(output) && throw(ArgumentError(
            "$description is not a regular file: $output",
        ))
    end

    if !force
        ispath(particle_output) && throw(ArgumentError(
            "particle output already exists: $particle_output (use --force)",
        ))
        ispath(decay_output) && throw(ArgumentError(
            "decay output already exists: $decay_output (use --force)",
        ))
    end
    return nothing
end

function _temporaryoutput(write_output, path::AbstractString)
    parent = dirname(abspath(path))
    mkpath(parent)
    temporary_path, io = mktemp(parent)
    try
        write_output(io)
        flush(io)
        close(io)
        return temporary_path
    catch
        isopen(io) && close(io)
        rm(temporary_path; force = true)
        rethrow()
    end
end

function _writecanonical(
        source,
        particle_output::AbstractString,
        decay_output::AbstractString;
        force::Bool = false,
    )
    particle_temporary = _temporaryoutput(particle_output) do io
        _writeparticles(io, source.catalog)
    end
    decay_temporary = try
        _temporaryoutput(decay_output) do io
            _writedecays(io, source.network)
        end
    catch
        rm(particle_temporary; force = true)
        rethrow()
    end

    try
        mv(particle_temporary, particle_output; force)
        mv(decay_temporary, decay_output; force)
    catch
        ispath(particle_temporary) && rm(particle_temporary; force = true)
        ispath(decay_temporary) && rm(decay_temporary; force = true)
        rethrow()
    end
    return source
end

"""Convert and merge one or more AZYHYDRO combined files."""
function convert_azyhydro(
        input_paths::AbstractVector{<:AbstractString},
        particle_output::AbstractString,
        decay_output::AbstractString;
        force::Bool = false,
    )
    isempty(input_paths) && throw(ArgumentError(
        "AZYHYDRO conversion needs at least one input file",
    ))
    _validatetargets(
        particle_output,
        decay_output,
        input_paths;
        force,
    )
    source = _loadazyhydro(input_paths)
    return _writecanonical(
        source,
        particle_output,
        decay_output;
        force,
    )
end

"""Convert THERMINATOR particle and decay files, applying optional CG data."""
function convert_therminator(
        particle_input::AbstractString,
        decay_input::AbstractString,
        particle_output::AbstractString,
        decay_output::AbstractString;
        cgc_path::Union{Nothing, AbstractString} = nothing,
        force::Bool = false,
    )
    inputs = cgc_path === nothing ?
        String[particle_input, decay_input] :
        String[particle_input, decay_input, cgc_path]
    _validatetargets(
        particle_output,
        decay_output,
        inputs;
        force,
    )
    source = _loadtherminator(particle_input, decay_input; cgc_path)
    return _writecanonical(
        source,
        particle_output,
        decay_output;
        force,
    )
end

function _parsearguments(arguments)
    isempty(arguments) && throw(ArgumentError(USAGE))
    arguments[1] in ("-h", "--help") && return nothing

    format = arguments[1]
    format in ("azyhydro", "therminator") || throw(ArgumentError(
        "unknown input format $(repr(format))\n\n$USAGE",
    ))

    positional = String[]
    options = Dict{String, String}()
    force = false
    index = 2
    while index <= length(arguments)
        argument = arguments[index]
        if argument == "--force"
            force && throw(ArgumentError("--force was supplied more than once"))
            force = true
            index += 1
        elseif argument in ("--particles-out", "--decays-out", "--cgc")
            haskey(options, argument) && throw(ArgumentError(
                "$argument was supplied more than once",
            ))
            index < length(arguments) || throw(ArgumentError(
                "$argument requires a path",
            ))
            options[argument] = arguments[index + 1]
            index += 2
        elseif startswith(argument, "--")
            throw(ArgumentError("unknown option $argument"))
        else
            push!(positional, argument)
            index += 1
        end
    end

    particle_output = get(options, "--particles-out", nothing)
    particle_output === nothing && throw(ArgumentError(
        "--particles-out is required",
    ))
    decay_output = get(options, "--decays-out", nothing)
    decay_output === nothing && throw(ArgumentError(
        "--decays-out is required",
    ))

    cgc_path = get(options, "--cgc", nothing)
    format == "azyhydro" && cgc_path !== nothing && throw(ArgumentError(
        "--cgc is valid only for THERMINATOR input",
    ))
    if format == "therminator" && length(positional) != 2
        throw(ArgumentError(
            "THERMINATOR conversion needs PARTICLES and DECAYS inputs",
        ))
    end

    return (; format, positional, particle_output, decay_output, cgc_path, force)
end

function main(arguments = ARGS)
    parsed = _parsearguments(arguments)
    if parsed === nothing
        println(USAGE)
        return nothing
    end

    source = if parsed.format == "azyhydro"
        convert_azyhydro(
            parsed.positional,
            parsed.particle_output,
            parsed.decay_output;
            force = parsed.force,
        )
    else
        convert_therminator(
            parsed.positional[1],
            parsed.positional[2],
            parsed.particle_output,
            parsed.decay_output;
            cgc_path = parsed.cgc_path,
            force = parsed.force,
        )
    end

    println(
        "wrote $(length(source.catalog.byid)) particles to " *
            parsed.particle_output,
    )
    channel_count = sum(length, values(source.network.byparent); init = 0)
    println("wrote $channel_count decay channels to $(parsed.decay_output)")
    return nothing
end

end # module DecayDataConverter

if abspath(PROGRAM_FILE) == @__FILE__
    DecayDataConverter.main(ARGS)
end
