#!/usr/bin/env julia

"""
Restore charge-conjugation symmetry in a canonical decay network.

A self-conjugate parent -- one whose antiparticle is itself -- must decay
symmetrically under C: every channel needs a mirror with the same branching
ratio. In `QM2016Plus`, 103 quark-model parents violate this. For example

    rho(1921)3(0)   id 5000088,  Q = 0,  self-conjugate
        BR 0.0379  ->  rho-  pi+  pi0      no rho+ pi- pi0 counterpart
        BR 0.0110  ->  rho+  pi-
        BR 0.0076  ->  rho-  pi+           mirror channel, different BR

Each channel conserves charge on its own, which is why `validate` accepts them;
only the ensemble is wrong. The consequence is measurable: yields computed with
`ThermalModel` drift by dQ = -0.237 over the full list against 1e-13 for the
PDG-numbered layer, because feed-down hands a charged species more than its
antiparticle.

The repair averages each channel with its mirror,

    BR'(c) = BR'(cbar) = (BR(c) + BR(cbar)) / 2

adding the mirror where it is missing. This leaves every parent's total
branching ratio unchanged, since conjugation is a bijection on the channel set,
so nothing downstream is renormalized.

Conjugate parent *pairs* are already consistent -- all 665 of them -- so only
self-conjugate parents are touched.

    julia --project=. tools/symmetrize_conjugation.jl \\
        data/decays_light_qm.dat data/decays_light_qm_csym.dat \\
        data/particles_light_pdg.dat data/particles_light_qm.dat

Pass every particle file the decays refer to: conjugation is resolved by
looking for `-id` in the catalog, so a partial catalog would read pi+ as its
own antiparticle. The catalogs are read but never modified -- the output pairs
with the same particle files as its input.
"""

isdefined(Main, :CascadeTables) ||
    include(joinpath(dirname(@__DIR__), "CascadeTables.jl"))
using .CascadeTables
using Printf

"Antiparticle ID, or the particle itself when it is its own antiparticle."
conjugateid(catalog, particle_id) =
    haskey(catalog, -particle_id) ? -particle_id : particle_id

channelkey(daughters) = Tuple(sort(collect(daughters)))
conjugatekey(catalog, daughters) =
    Tuple(sort([conjugateid(catalog, d) for d in daughters]))

"""
    symmetrize(catalog, network) -> (channels_by_parent, repaired)

Branching ratios with C symmetry restored on self-conjugate parents, and the
sorted IDs of the parents that needed it.
"""
function symmetrize(catalog, network)
    result = Dict{Int, Vector{DecayChannel}}()
    repaired = Int[]

    for (parent_id, channels) in network.byparent
        selfchannel(c) = length(c.daughters) == 1 && only(c.daughters) == parent_id
        if conjugateid(catalog, parent_id) != parent_id
            result[parent_id] = copy(channels)
            continue
        end

        # Collapse to branching ratio per distinct final state, keeping any
        # self-channel aside: it marks a terminal species, not a decay.
        terminal = filter(selfchannel, channels)
        physical = filter(!selfchannel, channels)
        ratios = Dict{Tuple, Float64}()
        for channel in physical
            key = channelkey(channel.daughters)
            ratios[key] = get(ratios, key, 0.0) + channel.br
        end

        mirrored = Dict{Tuple, Float64}()
        for key in keys(ratios)
            mirrored[conjugatekey(catalog, key)] = 0.0
        end
        merged = merge(mirrored, ratios)          # union of a set and its mirror
        balanced = Dict(
            key => (get(merged, key, 0.0) +
                    get(merged, conjugatekey(catalog, key), 0.0)) / 2
            for key in keys(merged)
        )

        changed = any(
            abs(get(balanced, key, 0.0) - get(ratios, key, 0.0)) > 1.0e-12
            for key in union(keys(balanced), keys(ratios))
        )
        changed && push!(repaired, parent_id)

        rebuilt = DecayChannel[]
        for key in sort!(collect(keys(balanced)))
            balanced[key] > 0 || continue
            push!(rebuilt, DecayChannel(parent_id, balanced[key], collect(key)))
        end
        append!(rebuilt, terminal)
        result[parent_id] = rebuilt
    end

    return result, sort!(repaired)
end

function write_decays(path, channels_by_parent, source)
    open(path, "w") do io
        println(io, "# FastReso canonical decays v1")
        println(io, "# generated by tools/symmetrize_conjugation.jl")
        println(io, "# source: $source")
        println(io, "# charge-conjugation symmetry restored on self-conjugate parents")
        println(io, "# parent n_daughters branching_fraction daughters...")
        for parent_id in sort!(collect(keys(channels_by_parent)))
            for channel in channels_by_parent[parent_id]
                # Build the fields as strings: vcat would promote the integer
                # IDs and daughter count to Float64 alongside the branching
                # ratio, writing "2.0" where the reader expects "2".
                fields = [string(parent_id), string(length(channel.daughters)),
                          string(channel.br)]
                append!(fields, string.(channel.daughters))
                println(io, join(fields, " "))
            end
        end
    end
end

function main(arguments)
    length(arguments) >= 3 || error(
        "usage: julia tools/symmetrize_conjugation.jl DECAYS OUTPUT PARTICLES...",
    )
    decay_path, output_path = arguments[1], arguments[2]
    catalog = reduce(merge, readparticles.(arguments[3:end])).byid
    network = readdecays(decay_path)

    # The catalog must cover every daughter, not just the parents in this
    # layer. `conjugateid` reads a missing -id as "self-conjugate", so a
    # partial catalog silently reports pi+ as its own antiparticle and repairs
    # far fewer parents than it should -- 16 instead of 103, when the light
    # layer's particles are absent.
    unknown = Set{Int}()
    for channels in values(network.byparent), channel in channels
        for daughter_id in channel.daughters
            haskey(catalog, daughter_id) || push!(unknown, daughter_id)
        end
    end
    isempty(unknown) || error(
        "catalog is missing $(length(unknown)) daughter IDs, so conjugation " *
        "cannot be resolved: $(join(sort!(collect(unknown))[1:min(end, 8)], ", "))" *
        " -- pass every particle file the decays refer to",
    )

    channels_by_parent, repaired = symmetrize(catalog, network)
    write_decays(output_path, channels_by_parent, basename(decay_path))

    before = sum(length, values(network.byparent))
    after = sum(length, values(channels_by_parent))
    @printf("repaired %d self-conjugate parents; %d -> %d channel rows\n",
            length(repaired), before, after)
    @printf("wrote %s\n", output_path)
    return nothing
end

if abspath(PROGRAM_FILE) == @__FILE__
    main(ARGS)
end
